/**
 * Writes src/keys/blowfish-pi.ts: Blowfish's initial P-array and S-boxes,
 * which are the hexadecimal digits of π's fractional part, 1042 words of
 * them. Worked out here with Machin's formula rather than pasted from
 * somewhere, so the table can be regenerated and checked by anyone:
 *
 *   pnpm tsx scripts/blowfish-constants.ts
 */

import { writeFileSync } from 'node:fs';

const WORDS = 18 + 4 * 256;
const DIGITS = WORDS * 8;
const GUARD = 64n;
const BITS = BigInt(DIGITS * 4) + GUARD;

/** atan(1/x) scaled by 2^BITS, from its Taylor series. */
function arctanInverse(x: bigint): bigint {
  const one = 1n << BITS;
  let power = one / x;
  let sum = power;
  const square = x * x;
  for (let n = 3n, sign = -1n; power !== 0n; n += 2n, sign = -sign) {
    power /= square;
    sum += (sign * power) / n;
  }
  return sum;
}

const pi = 16n * arctanInverse(5n) - 4n * arctanInverse(239n);
const fraction = (pi - (3n << BITS)) >> GUARD;
const hex = fraction.toString(16).padStart(DIGITS, '0');

if (!hex.startsWith('243f6a88')) throw new Error(`π came out wrong: ${hex.slice(0, 16)}`);

const lines: string[] = [];
for (let at = 0; at < hex.length; at += 96) lines.push(`  '${hex.slice(at, at + 96)}'`);

writeFileSync(
  new URL('../src/keys/blowfish-pi.ts', import.meta.url),
  `/**
 * Blowfish's initial state: the first ${DIGITS} hexadecimal digits of π's
 * fractional part, 18 words of P-array and then four S-boxes of 256.
 * Generated by scripts/blowfish-constants.ts; do not edit.
 */
export const PI_HEX =
${lines.join(' +\n')};
`,
);
console.log(
  `wrote ${WORDS} words; P[17] = ${hex.slice(17 * 8, 18 * 8)}, S0[0] = ${hex.slice(18 * 8, 19 * 8)}`,
);
